#!/bin/bash
# shim-coverage.sh ENGINE_DIR SHIM_DIR [ENGINE_FILE ...]
#
# Does every shimmed module still define everything the engine asks of it?
#
# WHY THIS EXISTS, GIVEN THE BUILD ALREADY FAILS. It does fail, and loudly -- run.sh turns a
# build error into "the shims need updating" and exit 2. But the OCaml compiler stops at the
# FIRST unbound name, so the operator fixes one symbol, re-runs, waits, and meets the next one.
# On 2026-11-24 that is exactly what happened: the reported failure was
# Config.pulse_opaque_max_size at PulseFormulaTerm.ml:478, and behind it sat
# Config.pulse_opaque_max_depth and Var.mk_fresh. Two of the three were invisible until the one
# in front of them was fixed. This names the whole set in one pass, before the build, so a
# shim update is one edit instead of a guessing game.
#
# It is a COVERAGE check, not a type check. It answers "is this name defined in the shim at
# all", and deliberately not "with the right type or the right value" -- the build settles the
# type and only a human settles the value. The caps in Config.ml are the clearest case: this
# check cannot tell that 256 has drifted to 512, which is why that shim carries a comment
# saying so rather than relying on this.
#
# HOW IT CAN BE WRONG, stated so a green run is read for what it is:
#   - a reference written as `let open Config in max_size` is NOT seen (no qualified name), so
#     drift of that shape slips through to the build, which still catches it;
#   - a `Module.name` inside a comment or a string IS seen, and would be reported as missing.
#     That direction is safe: it fails loudly and a human removes the false entry.
# Both are failures towards noise, never towards silence.
set -u
export LC_ALL=C

[ $# -ge 3 ] || { echo "usage: shim-coverage.sh ENGINE_DIR SHIM_DIR ENGINE_FILE..." >&2; exit 2; }
ENGINE_DIR=$1; SHIM_DIR=$2; shift 2

[ -d "$ENGINE_DIR" ] || { echo "shim-coverage: no engine directory at $ENGINE_DIR" >&2; exit 2; }
[ -d "$SHIM_DIR" ]   || { echo "shim-coverage: no shim directory at $SHIM_DIR" >&2; exit 2; }

# The modules we are responsible for: one per shim file. A reference to a module we do NOT shim
# (Stdlib, Format, Z, ...) is not our business and is skipped.
shimmed=$(for f in "$SHIM_DIR"/*.ml; do [ -e "$f" ] || continue; basename "$f" .ml; done | sort -u)
[ -n "$shimmed" ] || { echo "shim-coverage: no shims in $SHIM_DIR" >&2; exit 2; }

missing=""
checked=0
aliases_seen=0
for engine in "$@"; do
  src="$ENGINE_DIR/$engine"
  [ -f "$src" ] || { echo "shim-coverage: engine file missing: $src" >&2; exit 2; }
  # MODULE ALIASES, resolved per file. The engine rarely spells a shimmed module by its own
  # name: PulseFormulaTerm.ml line 13 is `module Var = PulseFormulaVar`, and every use is then
  # `Var.mk_fresh`. The first version of this check skipped those as "not a module we shim" and
  # reported ok while Var.mk_fresh was missing from the shim -- which is the exact symbol that
  # was hiding behind Config.pulse_opaque_max_size on 2026-11-24. A coverage check blind to the
  # spelling the code actually uses is worse than none, because it reads green.
  # Scoped per file, because an alias is: two files may bind the same short name differently.
  alias_map=$(grep -oE '^[[:space:]]*module[[:space:]]+[A-Z][A-Za-z0-9_]*[[:space:]]*=[[:space:]]*[A-Z][A-Za-z0-9_]*[[:space:]]*$' "$src" \
              | sed -E 's/^[[:space:]]*module[[:space:]]+([A-Za-z0-9_]+)[[:space:]]*=[[:space:]]*([A-Za-z0-9_]+)[[:space:]]*$/\1 \2/')
  [ -n "$alias_map" ] && aliases_seen=$((aliases_seen + $(printf '%s\n' "$alias_map" | grep -c .)))
  # Qualified references, e.g. Config.pulse_opaque_max_size. Module names start upper-case and
  # the member lower-case: that is what distinguishes a value reference from a module path
  # (Var.Map) or a constructor (Typ.Tint), neither of which this check is about.
  while read -r ref; do
    [ -n "$ref" ] || continue
    mod=${ref%%.*}
    member=${ref#*.}
    # Resolve through the alias map, transitively but boundedly (module A = B = C).
    hops=0
    while [ "$hops" -lt 8 ]; do
      target=$(printf '%s\n' "$alias_map" | awk -v m="$mod" '$1 == m {print $2; exit}')
      [ -n "$target" ] || break
      mod=$target
      hops=$((hops + 1))
    done
    printf '%s\n' "$shimmed" | grep -qxF "$mod" || continue   # not a module we shim
    checked=$((checked + 1))
    # Defined as a value, a type, an external, or inside a module of that name in the shim --
    # OR GENERATED BY A ppx DERIVER. The shims lean on `type t = int [@@deriving compare, equal,
    # yojson_of]`, which produces `equal` and `yojson_of_t` with no `let` for this to find. The
    # first alias-aware version of this check duly reported both as missing against a tree that
    # builds and passes, and a check that fails on a correct tree is one people learn to skip --
    # the same habituation the harness exists to prevent. A deriver D is taken to define D,
    # D_t and t_of_D, which covers the three shapes these shims actually use.
    # The binder may carry `rec`/`nonrec` and, for a type, parameters: the shims really do write
    # `type nonrec 'a t = ...` (PulseSatUnsat) and `type 'a singleton_or_more` (IContainer). A
    # pattern that only allowed `type t` reported PulseSatUnsat.t missing against a tree that
    # builds, which is the same read-green-on-a-correct-tree failure as the deriver case below.
    defined=no
    grep -qE "^[[:space:]]*(let|and|external|type|module)[[:space:]]+((rec|nonrec)[[:space:]]+)?((\('[a-z]+(,[[:space:]]*'[a-z]+)*\)|'[a-z]+)[[:space:]]+)?${member}\b" \
      "$SHIM_DIR/$mod.ml" && defined=yes
    if [ "$defined" = no ]; then
      for d in $(grep -ohE '\[@@deriving[^]]*\]' "$SHIM_DIR/$mod.ml" 2>/dev/null \
                 | sed -E 's/\[@@deriving//; s/\]//; s/,/ /g'); do
        case $member in
          "$d"|"${d}_t"|"t_of_${d}") defined=yes; break ;;
        esac
      done
    fi
    if [ "$defined" = no ]; then
      case $missing in
        *"$mod.$member "*) ;;                                  # already reported once
        *) missing="$missing$mod.$member " ;;
      esac
    fi
  done <<EOF
$(grep -ohE '\b[A-Z][A-Za-z0-9_]*\.[a-z_][A-Za-z0-9_'"'"']*' "$src" | sort -u)
EOF
done

if [ "$checked" -eq 0 ]; then
  # A check that examined nothing must not report success: that is the shape of green this
  # whole harness exists to refuse. If the engine genuinely stopped using every shimmed module
  # the shims are dead code and someone should say so deliberately.
  echo "shim-coverage: examined 0 qualified references to shimmed modules across $# engine file(s)." >&2
  echo "  Either the engine no longer uses the shims, or this check stopped matching. Refusing" >&2
  echo "  to report coverage on nothing." >&2
  exit 2
fi

if [ -n "$missing" ]; then
  echo "shim-coverage: the shims have fallen behind the engine. Missing from $SHIM_DIR:" >&2
  for m in $missing; do echo "    $m" >&2; done
  echo "  Add each one to its shim in the SAME commit as the engine change that introduced it." >&2
  echo "  Values matter as much as names: see the comment in shims/Config.ml." >&2
  exit 1
fi

echo "shim-coverage: ok, $checked qualified reference(s) to shimmed modules, all defined."
